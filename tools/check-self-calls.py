problems = []
for root, dirs, files in os.walk(src):
    for name in files:
        if not name.endswith(".lua"):
            continue
        path = os.path.join(root, name)
        with open(path, "r", encoding="utf-8") as handle:
            for number, line in enumerate(handle, 1):
                stripped = line.strip()
                if stripped.startswith("--"):
                    continue
                for match in pattern.finditer(line):
                    field = match.group(0).split("(")[0].strip()
                    if field in allowed:
                        continue
                    problems.append("%s:%d  %s" % (os.path.relpath(path, src), number, stripped))

if problems:
    print("suspected method calls without self:")
    for problem in problems:
        print("  " + problem)
    sys.exit(1)

print("self-call check clean")
